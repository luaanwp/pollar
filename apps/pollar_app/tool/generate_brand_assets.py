"""Generate the approved Pollar mark and outlined Inter SemiBold wordmark.

Run from any directory with Python + fonttools, then render_brand_assets.cjs.
All symbols, Flutter geometry and Android vectors share brand_geometry.json.
"""
import json
from pathlib import Path

from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.svgLib.path import parse_path
from fontTools.ttLib import TTFont

APP = Path(__file__).resolve().parents[1]
BRAND = APP / "assets/brand"
BRAND.mkdir(parents=True, exist_ok=True)
geometry = json.loads(Path(__file__).with_name("brand_geometry.json").read_text())
path = geometry["path"]
width, height = geometry["width"], geometry["height"]


def svg(name, viewbox, contents, title):
    (BRAND / name).write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" '
        f'role="img" aria-label="{title}">\n{contents}\n</svg>\n', encoding="utf-8"
    )


def mark(color, transform=""):
    return f'<path fill="{color}" fill-rule="evenodd" transform="{transform}" d="{path}"/>'


for color in ["teal", "mint"]:
    svg(f"pollar-symbol-{color}.svg", f"0 0 {width} {height}", mark(geometry[color]), "Pollar")

font = TTFont(APP / "assets/fonts/inter/Inter-SemiBold.ttf")
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
units = font["head"].unitsPerEm
scale = 96 / units
cursor = 0
letters = []
for letter in "Pollar":
    name = cmap[ord(letter)]
    pen = SVGPathPen(glyphs)
    glyphs[name].draw(pen)
    letters.append(f'<path transform="translate({cursor} 0)" d="{pen.getCommands()}"/>')
    cursor += font["hmtx"][name][0]
font.close()
total_width = round(104 + cursor * scale + 8, 3)
for color in ["teal", "mint"]:
    content = mark(geometry[color], f"translate(4 8) scale({88 / height})")
    content += (
        f'\n<g fill="{geometry[color]}" transform="translate(104 88) scale({scale} {-scale})">'
        + "".join(letters) + "</g>"
    )
    svg(f"pollar-logo-{color}.svg", f"0 0 {total_width} 104", content, "Pollar")

icon_scale = 580 / height
icon_x = (1024 - width * icon_scale) / 2
svg(
    "pollar-app-icon.svg", "0 0 1024 1024",
    f'<path fill="{geometry["dark"]}" d="M0 0H1024V1024H0Z"/>\n'
    + mark(geometry["mint"], f"translate({icon_x} 222) scale({icon_scale})"), "Pollar",
)

# Generated Dart coordinates avoid a runtime SVG dependency or font dependency
# for the symbol. The wordmark uses the already bundled Inter SemiBold.
recording = RecordingPen()
parse_path(path, recording)
lines = [
    "// Generated by tool/generate_brand_assets.py. Do not edit.",
    "import 'dart:ui';", "", "Path createPollarMarkPath() => Path()",
    "  ..fillType = PathFillType.evenOdd",
]
for command, points in recording.value:
    flat = ", ".join(str(round(value, 6)) for point in points for value in point)
    method = {"moveTo": "moveTo", "lineTo": "lineTo", "curveTo": "cubicTo", "closePath": "close"}[command]
    lines.append(f"  ..{method}({flat})")
lines[-1] += ";"
(APP / "lib/shared/presentation/pollar_brand_geometry.dart").write_text("\n".join(lines) + "\n", encoding="utf-8")

res = APP / "android/app/src/main/res"
(res / "values/pollar_brand_colors.xml").write_text(
    '<resources>\n'
    f'  <color name="pollar_launcher_background">{geometry["dark"]}</color>\n'
    '</resources>\n', encoding="utf-8"
)
(res / "drawable").mkdir(exist_ok=True)
adaptive_scale = 48 / height
adaptive_x = (108 - width * adaptive_scale) / 2
(res / "drawable/pollar_launcher_foreground.xml").write_text(
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
    f'  <group android:translateX="{adaptive_x}" android:translateY="30" android:scaleX="{adaptive_scale}" android:scaleY="{adaptive_scale}">\n'
    f'    <path android:fillColor="{geometry["mint"]}" android:fillType="evenOdd" android:pathData="{path}"/>\n'
    '  </group>\n</vector>\n', encoding="utf-8"
)
for qualifier, monochrome in [("mipmap-anydpi-v26", False), ("mipmap-anydpi-v33", True)]:
    (res / qualifier).mkdir(exist_ok=True)
    (res / qualifier / "ic_launcher.xml").write_text(
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '  <background android:drawable="@color/pollar_launcher_background"/>\n'
        '  <foreground android:drawable="@drawable/pollar_launcher_foreground"/>\n'
        + ('  <monochrome android:drawable="@drawable/pollar_launcher_foreground"/>\n' if monochrome else '')
        + '</adaptive-icon>\n', encoding="utf-8"
    )
print(f"Generated Pollar vectors, outlined wordmarks, Dart path and Android adaptive icons in {BRAND}")
